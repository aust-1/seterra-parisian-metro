package com.parismetro.quiz.data

import com.parismetro.quiz.domain.model.MapPoint
import java.io.File
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

class GeographyParserTest {

    @Test
    fun `parses flat rings into points and drops degenerate rings`() {
        val geography = parseGeography(
            """{"source":"x","seine":[[0,0,10,0,10,10],[1,1,2,2]],"peripherique":[5,5,6,5,6,6]}"""
        )

        assertEquals(1, geography.seineRings.size)
        assertEquals(listOf(MapPoint(0f, 0f), MapPoint(10f, 0f), MapPoint(10f, 10f)), geography.seineRings[0])
        assertEquals(3, geography.peripherique.size)
    }

    @Test(expected = IllegalArgumentException::class)
    fun `rejects a ring with an odd number of coordinates`() {
        parseGeography("""{"seine":[[0,0,10]],"peripherique":[]}""")
    }

    // --- The bundled asset, generated by scripts/generate-geography.py -------------------

    private val bundled by lazy {
        val path = listOf("src/main/assets/metro-data/geography.json", "app/src/main/assets/metro-data/geography.json")
            .map(::File)
            .first { it.exists() }
        parseGeography(path.readText())
    }

    @Test
    fun `the Seine splits around its islands`() {
        val windings = bundled.seineRings.map { signedArea(it) > 0 }
        assertTrue("riverbanks expected", windings.any { it })
        assertTrue("islands (reverse winding) expected", windings.any { !it })

        // Cité station stands on Île de la Cité: dry, with water on both arms around it.
        assertEquals(0, winding(bundled.seineRings, 664f, 479f))
        assertEquals(1, winding(bundled.seineRings, 635.3f, 464.6f)) // grand bras, au Pont Neuf
        assertEquals(0, winding(bundled.seineRings, 710f, 493.6f)) // Île Saint-Louis
    }

    @Test
    fun `the Périphérique rings central Paris and leaves La Défense out`() {
        val ring = listOf(bundled.peripherique)
        assertTrue(bundled.peripherique.size > 50)
        assertEquals(1, Math.abs(winding(ring, 664f, 461f))) // Châtelet
        assertEquals(0, winding(ring, 115f, 312f)) // La Défense - Grande Arche
    }

    @Test
    fun `every point stays within the map plus its clipping margin`() {
        val points = bundled.seineRings.flatten() + bundled.peripherique
        assertFalse(points.isEmpty())
        points.forEach { p ->
            assertTrue("$p", p.x in -41f..1441f && p.y in -41f..1161f)
        }
    }

    private fun signedArea(ring: List<MapPoint>): Float =
        ring.indices.sumOf { i ->
            val a = ring[i]
            val b = ring[(i + 1) % ring.size]
            (a.x * b.y - b.x * a.y).toDouble()
        }.toFloat() / 2f

    /** Non-zero winding number of (x, y) over all [rings] - 0 means "outside". */
    private fun winding(rings: List<List<MapPoint>>, x: Float, y: Float): Int {
        var w = 0
        rings.forEach { ring ->
            ring.indices.forEach { i ->
                val a = ring[i]
                val b = ring[(i + 1) % ring.size]
                val side = (b.x - a.x) * (y - a.y) - (x - a.x) * (b.y - a.y)
                if (a.y <= y) {
                    if (b.y > y && side > 0) w++
                } else if (b.y <= y && side < 0) {
                    w--
                }
            }
        }
        return w
    }
}
